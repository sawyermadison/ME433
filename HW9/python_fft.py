# ============================================================
# LOAD CSV FILES
# ============================================================

files = ['sigA.csv', 'sigB.csv', 'sigD.csv']
signals = {}

for filename in files:

    t = []
    data = []

    with open(filename) as f:
        reader = csv.reader(f)

        for row in reader:
            t.append(float(row[0]))
            data.append(float(row[1]))

    total_time = t[-1] - t[0]
    num_samples = len(t)
    sample_rate = num_samples / total_time

    signals[filename] = {
        't': t,
        'data': data,
        'sample_rate': sample_rate
    }

