# ============================================================
# FIR FILTER INFORMATION
# Store separate FIR info for each CSV
# ============================================================

fir_info = {

    'sigA.csv': {
        'type': 'Low Pass FIR',
        'cutoff': '100 Hz',
        'bandwidth': '500 Hz'
    },

    'sigB.csv': {
        'type': 'Low Pass FIR',
        'cutoff': '100 Hz',
        'bandwidth': '200 Hz'
    },

    'sigD.csv': {
        'type': 'Low Pass FIR',
        'cutoff': '50 Hz',
        'bandwidth': '50 Hz'
    }
}

# ============================================================
# PROCESS EACH SIGNAL
# ============================================================

for filename in signals:

    t = signals[filename]['t']
    data = signals[filename]['data']
    fs = signals[filename]['sample_rate']

    # ========================================================
    # MOVING AVERAGE FILTER (MAF)
    # ========================================================

    t_MAF = []
    data_MAF = []

    for i in range(len(data)):

        if i > num_averaged:

            t_MAF.append(t[i])

            data_MAF.append(
                statistics.mean(data[i-num_averaged:i])
            )

    # ========================================================
    # IIR FILTER
    # ========================================================

    A, B = filter_weights[filename]

    data_IIR = [data[0]]

    for i in range(1, len(data)):

        new_value = A * data_IIR[i-1] + B * data[i]

        data_IIR.append(new_value)

    # ========================================================
    # CUSTOM FIR FILTER
    # ========================================================

    # ========================================================
    # GET FIR FILTER INFO
    # ========================================================

    fir_type = fir_info[filename]['type']
    fir_cutoff = fir_info[filename]['cutoff']
    fir_bandwidth = fir_info[filename]['bandwidth']

    coeffs = fir_coefficients[filename]

    data_FIR = []

    num_coeffs = len(coeffs)

    for i in range(len(data)):

        filtered_value = 0

        for k in range(num_coeffs):

            if i-k >= 0:

                filtered_value += coeffs[k] * data[i-k]

        data_FIR.append(filtered_value)

    # ========================================================
    # FFT OF ORIGINAL SIGNAL
    # ========================================================

    y = data
    n = len(y)

    Y = np.fft.fft(y) / n
    Y = Y[:n//2]

    frq = np.fft.fftfreq(n, d=1/fs)
    frq = frq[:n//2]

    # ========================================================
    # FFT OF MAF SIGNAL
    # ========================================================

    y_MAF = data_MAF
    n_MAF = len(y_MAF)

    sample_rate_MAF = len(t_MAF) / (t_MAF[-1] - t_MAF[0])

    Y_MAF = np.fft.fft(y_MAF) / n_MAF
    Y_MAF = Y_MAF[:n_MAF//2]

    frq_MAF = np.fft.fftfreq(n_MAF, d=1/sample_rate_MAF)
    frq_MAF = frq_MAF[:n_MAF//2]

    # ========================================================
    # FFT OF IIR SIGNAL
    # ========================================================

    y_IIR = data_IIR
    n_IIR = len(y_IIR)

    Y_IIR = np.fft.fft(y_IIR) / n_IIR
    Y_IIR = Y_IIR[:n_IIR//2]

    frq_IIR = np.fft.fftfreq(n_IIR, d=1/fs)
    frq_IIR = frq_IIR[:n_IIR//2]

    # ========================================================
    # FFT OF FIR SIGNAL
    # ========================================================

    y_FIR = data_FIR
    n_FIR = len(y_FIR)

    Y_FIR = np.fft.fft(y_FIR) / n_FIR
    Y_FIR = Y_FIR[:n_FIR//2]

    frq_FIR = np.fft.fftfreq(n_FIR, d=1/fs)
    frq_FIR = frq_FIR[:n_FIR//2]

    # ========================================================
    # FIGURE 1 : ORIGINAL VS MAF
    # ========================================================

    fig1, (ax1, ax2) = plt.subplots(2, 1)

    fig1.suptitle(
        f"{filename.split('.')[0]} : Moving Average Filter\n"
        f"{num_averaged} Samples Averaged"
    )

    # Time Domain
    ax1.plot(t, data, 'k', label='Original')
    ax1.plot(t_MAF, data_MAF, 'r', label='MAF')

    ax1.set_xlabel('Time')
    ax1.set_ylabel('Amplitude')
    ax1.legend()

    # Frequency Domain
    ax2.loglog(frq, abs(Y), 'k', label='Original FFT')
    ax2.loglog(frq_MAF, abs(Y_MAF), 'r', label='MAF FFT')

    ax2.set_xlabel('Frequency (Hz)')
    ax2.set_ylabel('|Y(freq)|')
    ax2.legend()

    plt.tight_layout()

    # ========================================================
    # FIGURE 2 : ORIGINAL VS IIR
    # ========================================================

    fig2, (ax3, ax4) = plt.subplots(2, 1)

    fig2.suptitle(
        f"{filename.split('.')[0]} : IIR Low Pass Filter\n"
        f"A = {A}, B = {B}"
    )

    # Time Domain
    ax3.plot(t, data, 'k', label='Original')
    ax3.plot(t, data_IIR, 'r', label='IIR')

    ax3.set_xlabel('Time')
    ax3.set_ylabel('Amplitude')
    ax3.legend()

    # Frequency Domain
    ax4.loglog(frq, abs(Y), 'k', label='Original FFT')
    ax4.loglog(frq_IIR, abs(Y_IIR), 'r', label='IIR FFT')

    ax4.set_xlabel('Frequency (Hz)')
    ax4.set_ylabel('|Y(freq)|')
    ax4.legend()

    plt.tight_layout()

    # ========================================================
    # FIGURE 3 : ORIGINAL VS CUSTOM FIR
    # ========================================================

    fig3, (ax5, ax6) = plt.subplots(2, 1)

    fig3.suptitle(
        f"{filename.split('.')[0]} : {fir_type}\n"
        f"{num_coeffs} Coefficients | "
        f"Cutoff = {fir_cutoff} | "
        f"Bandwidth = {fir_bandwidth}"
    )

    # Time Domain
    ax5.plot(t, data, 'k', label='Original')
    ax5.plot(t, data_FIR, 'r', label='Custom FIR')

    ax5.set_xlabel('Time')
    ax5.set_ylabel('Amplitude')
    ax5.legend()

    # Frequency Domain
    ax6.loglog(frq, abs(Y), 'k', label='Original FFT')
    ax6.loglog(frq_FIR, abs(Y_FIR), 'r', label='FIR FFT')

    ax6.set_xlabel('Frequency (Hz)')
    ax6.set_ylabel('|Y(freq)|')
    ax6.legend()

    plt.tight_layout()

# ============================================================
# SHOW ALL FIGURES
# ============================================================

plt.show()